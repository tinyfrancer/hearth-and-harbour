/**
 * Who you fight in a dungeon, drawn in the game's own hand: rows of
 * characters with a legend each, outlined automatically, facing right, lit
 * from the upper left. Creatures are their own drawings at whatever size suits
 * them; people are posed bodies of their own, arms doing something, what they
 * hold held by the hand rule (the grip through a fist, something of it above
 * and below), eyes mirrored. Size carries threat: the rat is small, a deckhand
 * the hero's height, the giant crab wide and low, the captain a head taller
 * than anyone.
 *
 * Each foe's `feet` is where it stands on the ground, counted on the drawing
 * before its outline; the outline adds a pixel all round, which `foeFigure`
 * accounts for.
 */
import { outline, parseSprite, type Grid, type Legend } from './grid';
import type { Glow } from './raster';

export interface FoeDef {
  readonly rows: readonly string[];
  readonly legend: Legend;
  /** Where it stands, on the drawing (before the outline). */
  readonly feet: readonly [x: number, y: number];
  /** Lights it carries (a lit fuse), on the drawing; they shine at dusk. */
  readonly glows?: readonly Glow[];
}

