/** A foe's drawing, outlined, and its feet on the outlined picture. */
export function foeGrid(def: FoeDef): {
  grid: Grid;
  feet: { x: number; y: number };
  glows: Glow[];
} {
  const g = outline(parseSprite(def.rows, def.legend));
  const glows = (def.glows ?? []).map((l) => ({ ...l, x: l.x + 1.5, y: l.y + 1.5 }));
  return { grid: g, feet: { x: def.feet[0] + 1, y: def.feet[1] + 1 }, glows };
}
